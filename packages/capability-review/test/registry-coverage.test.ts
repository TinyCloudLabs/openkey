// Every TinyCloud core ability is classified (TC-799).
//
// Loads the node capability registry vendored in `@tinycloud/bootstrap`
// (installed locally, so this runs offline) and reviews each ability as a
// real ReCap request on a typical resource for its service. No registry
// ability may land in the `unknown` family or render "Unknown service".
//
// The same rows are checked in as `registry-inventory.md`. To refresh it
// after changing copy, run:
//   UPDATE_INVENTORY=1 bun test test/registry-coverage.test.ts

import { describe, expect, it } from "bun:test";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { CAPABILITY_REGISTRY } from "@tinycloud/bootstrap";

import {
  buildStatement,
  parseCapabilityReview,
  type CapabilityGrant,
  type SignerInfo,
} from "../src/index.js";
import type { ParseContext } from "../src/parse.js";
import {
  FIXTURE_META,
  makeRecapResource,
  siweWithResources,
} from "./fixtures/index.js";

const ACCOUNT = FIXTURE_META.address;
const OTHER = "0x2222222222222222222222222222222222222222";
const space = (name: string, owner = ACCOUNT) =>
  `tinycloud:pkh:eip155:${FIXTURE_META.chainId}:${owner}:${name}`;

// The resource each service is normally requested on. `<space>/<short>[/path]`
// is the wire form tinycloud-node emits.
const RESOURCE: Record<string, string> = {
  "tinycloud.kv": `${space("default")}/kv/notes/`,
  "tinycloud.sql": `${space("default")}/sql/notes`,
  "tinycloud.duckdb": `${space("default")}/duckdb/analytics`,
  "tinycloud.vfs": `${space("default")}/vfs/photos`,
  "tinycloud.hooks": `${space("default")}/hooks/notes/`,
  "tinycloud.capabilities": `${space("default")}/capabilities`,
  "tinycloud.delegation": `${space("account")}/delegation`,
  "tinycloud.encryption": `${space("default")}/encryption`,
  "tinycloud.space": `${space("courier")}/space`,
};

const signer: SignerInfo = {
  label: "Test signer",
  address: ACCOUNT,
  chainId: FIXTURE_META.chainId,
  provenance: "managed",
};

function review(resource: string, abilities: string[]): CapabilityGrant {
  const ctx: ParseContext = {
    message: siweWithResources([
      makeRecapResource({
        [resource]: Object.fromEntries(abilities.map((a) => [a, [{}]])),
      }),
    ]),
    signer,
    editable: true,
    metadataTrust: { status: "unsigned", reason: "no manifest" },
    reason: { text: "", source: "none" },
    requester: {
      displayName: "cli.tinycloud.xyz",
      verifiedOrigin: "https://cli.tinycloud.xyz",
      appId: null,
      manifestName: null,
      manifestNameProvenance: "none",
      manifestId: null,
      manifestIdProvenance: "none",
      manifestDigest: null,
      domainWarning: false,
      originWarning: false,
    },
  };
  const model = parseCapabilityReview(ctx);
  expect(model.protocol).toBe("tinycloud-siwe-recap");
  expect(model.permissions).toHaveLength(1);
  return model.permissions[0]!;
}

function reviewAbility(urn: string, service: string): CapabilityGrant {
  const resource = RESOURCE[service];
  if (!resource) {
    throw new Error(
      `No review resource for registry service ${service}; add it to RESOURCE`,
    );
  }
  return review(resource, [urn]);
}

function inventoryMarkdown(): string {
  const rows = CAPABILITY_REGISTRY.map((entry) => {
    const grant = reviewAbility(entry.urn, entry.service);
    const status =
      entry.status === "deprecated-alias"
        ? `alias of \`${entry.aliasOf}\``
        : entry.status;
    return `| \`${entry.urn}\` | ${status} | ${grant.displayLabel} | ${buildStatement(grant).primaryText} | ${grant.severity} |`;
  });
  return [
    "# TinyCloud core ability inventory",
    "",
    "How capability review presents each ability in the TinyCloud node",
    "registry (`@tinycloud/bootstrap` `CAPABILITY_REGISTRY`) when it is",
    "requested alone on the signer's own space. The label is the grant title,",
    "the description is the consent sentence. KV, SQL, DuckDB, hooks and VFS",
    "are shown on a named path in the `default` space, delegation on the",
    "`account` space and space operations on a space named `courier`. Other",
    "targets (another user's space, secrets spaces, whole-space admin) can",
    "change the row. Generated by `test/registry-coverage.test.ts`.",
    "",
    "| Ability | Status | Label | Description | Severity |",
    "| --- | --- | --- | --- | --- |",
    ...rows,
    "",
  ].join("\n");
}

describe("TinyCloud capability registry coverage", () => {
  it("loads a non-empty registry covering every core service", () => {
    const services = new Set(CAPABILITY_REGISTRY.map((entry) => entry.service));
    expect([...services].sort()).toEqual(Object.keys(RESOURCE).sort());
  });

  for (const entry of CAPABILITY_REGISTRY) {
    it(`classifies ${entry.urn}`, () => {
      const grant = reviewAbility(entry.urn, entry.service);
      expect(grant.family).not.toBe("unknown");
      expect(grant.displayLabel).not.toContain("Unknown service");
      expect(grant.displayLabel).not.toContain("Unrecognized");
    });
  }

  for (const entry of CAPABILITY_REGISTRY.filter((e) => e.aliasOf)) {
    it(`classifies alias ${entry.urn} like ${entry.aliasOf}`, () => {
      const alias = reviewAbility(entry.urn, entry.service);
      const target = reviewAbility(entry.aliasOf!, entry.service);
      expect(alias.family).toBe(target.family);
      expect(alias.severity).toBe(target.severity);
      expect(alias.displayLabel).toBe(target.displayLabel);
    });
  }

  it("presents tinycloud.space/host as a sensitive 'Create a space'", () => {
    const grant = reviewAbility("tinycloud.space/host", "tinycloud.space");
    expect(grant.family).toBe("space-create");
    expect(grant.displayLabel).toBe("Create a space");
    expect(grant.severity).toBe("sensitive");
    expect(buildStatement(grant).primaryText).toBe(
      "Create a new TinyCloud space",
    );
  });

  it("matches the checked-in inventory", () => {
    const path = fileURLToPath(
      new URL("../registry-inventory.md", import.meta.url),
    );
    const expected = inventoryMarkdown();
    if (process.env.UPDATE_INVENTORY === "1") writeFileSync(path, expected);
    expect(readFileSync(path, "utf8")).toBe(expected);
  });
});

describe("core services stay fail-closed off their known shapes", () => {
  it("an unregistered verb on a core service is unknown and elevated", () => {
    for (const [service, ability] of [
      ["tinycloud.space", "tinycloud.space/delete"],
      ["tinycloud.hooks", "tinycloud.hooks/fire"],
      ["tinycloud.duckdb", "tinycloud.duckdb/drop"],
      ["tinycloud.vfs", "tinycloud.vfs/chmod"],
    ] as const) {
      const grant = reviewAbility(ability, service);
      expect(grant.family).toBe("unknown");
      expect(grant.severity).not.toBe("standard");
      expect(buildStatement(grant).primaryText).toBe(
        `Perform ${ability} on ${service}`,
      );
    }
  });

  it("a known verb mixed with an unregistered one is unknown", () => {
    const grant = review(RESOURCE["tinycloud.hooks"]!, [
      "tinycloud.hooks/list",
      "tinycloud.hooks/exfiltrate",
    ]);
    expect(grant.family).toBe("unknown");
    expect(grant.severity).toBe("attention");
  });

  it("a mixed grant takes its most severe family", () => {
    const grant = review(RESOURCE["tinycloud.space"]!, [
      "tinycloud.space/info",
      "tinycloud.space/host",
    ]);
    expect(grant.family).toBe("space-create");
    expect(grant.severity).toBe("sensitive");
  });

  it("DuckDB on a secrets space stays unknown", () => {
    const grant = review(`${space("secrets")}/duckdb/catalog`, [
      "tinycloud.duckdb/read",
    ]);
    expect(grant.family).toBe("unknown");
    expect(grant.severity).toBe("attention");
  });

  it("hooks on a space without a known meaning stay unknown", () => {
    const grant = review(`${space("courier")}/hooks/notes/`, [
      "tinycloud.hooks/subscribe",
    ]);
    expect(grant.family).toBe("unknown");
  });

  it("another user's DuckDB data is cross-user, and admin stays sensitive", () => {
    const read = review(`${space("default", OTHER)}/duckdb/analytics`, [
      "tinycloud.duckdb/read",
    ]);
    expect(read.family).toBe("cross-app-data");
    expect(read.severity).toBe("attention");
    expect(buildStatement(read).primaryText).toBe(
      "Perform tinycloud.duckdb/read on tinycloud.duckdb",
    );
    const admin = review(`${space("default", OTHER)}/duckdb/analytics`, [
      "tinycloud.duckdb/import",
    ]);
    expect(admin.family).toBe("database-admin");
    expect(admin.severity).toBe("sensitive");
  });

  it("creating a space for another user stays sensitive", () => {
    const grant = review(`${space("courier", OTHER)}/space`, [
      "tinycloud.space/host",
    ]);
    expect(grant.family).toBe("space-create");
    expect(grant.severity).toBe("sensitive");
    expect(grant.displayLabel).toBe("Create a space for another user");
  });

  it("whole-space SQL admin stays unknown", () => {
    const grant = review(`${space("default")}/sql`, ["tinycloud.sql/admin"]);
    expect(grant.family).toBe("unknown");
    expect(grant.severity).toBe("sensitive");
  });
});
